"""Cross-Language Compatibility Gate: Daqiq PR #38 Verifier vs Rust-Generated Licenses.

Proves mathematically that licenses generated by the Rust engine (or following its
exact canonical JSON + Ed25519 specification) are 100% accepted by Daqiq PR #38.
"""

import datetime
import json
import os
import subprocess
import sys
import tempfile
import pytest

# Test hardware identifiers from Daqiq PR #38 test vectors
HWID_1 = "fp_v1:b8782278c4c15107a8fd2a5d21718e3328c8baeac5d1a3f0664701ac2983e52e"
HWID_2 = "fp_v1:cc12b7ba73d61e6240c106bb3239c09690102a0ca9f448497532733e8a5382cf"

ALL_FEATURE_KEYS = [
    "batches",
    "dashboard",
    "employees",
    "products",
    "reports",
    "sales",
    "services",
    "settings",
    "suppliers_payments",
    "upgrades",
]


def _get_daqiq_verifier():
    pr38_path = os.environ.get("DAQIQ_PR38_DIR", r"D:\Program.Files\Temp\daqiq_pr38")
    if not os.path.isdir(pr38_path):
        pytest.skip(f"Daqiq PR #38 directory not found at: {pr38_path}")

    if pr38_path not in sys.path:
        sys.path.insert(0, pr38_path)

    try:
        from licensing.license_verifier import LicenseVerifier
        from licensing.license_models import ValidationStatus
        from licensing.keys import KeyRegistry
        return LicenseVerifier, KeyRegistry, ValidationStatus
    except ImportError as e:
        pytest.skip(f"Could not import Daqiq PR #38 licensing module: {e}")


def test_golden_vector_parity():
    """Verify that Daqiq PR #38 accepts the official Golden Vector from spec section 3.2."""
    LicenseVerifier, KeyRegistry, ValidationStatus = _get_daqiq_verifier()

    raw_pub_b64 = "tZwFxuCGOF+WZqVF+PeKwpoIpOZovHLFRVSQxGaXJXA="
    sig_b64 = "kgrF5f89h9JBIHiQ55H5J+jZul3ZwC6NdeEDXtrlxMDWWlBr892vliqLsTxPD0q+RlEJaXsIQZUSjaevKSGjCA=="

    payload = {
        "customer": {
            "contact": "+989120000000",
            "name": "فروشگاه تستی نمونه",
            "organization": "مجموعه آزمایشی",
        },
        "device_fingerprints": [HWID_1],
        "expires_at": None,
        "features": {k: True for k in ALL_FEATURE_KEYS},
        "format_version": 1,
        "issued_at": "2026-11-22T00:00:00Z",
        "key_id": "daqiq-test-v1",
        "license_id": "LIC-2026-TEST01",
        "license_type": "perpetual",
        "max_app_version": None,
        "max_devices": 1,
        "min_app_version": "4.9.0",
        "not_before": "2026-11-22T00:00:00Z",
        "product_id": "daqiq.desktop",
    }

    envelope_doc = {
        "envelope_version": 1,
        "algorithm": "Ed25519",
        "key_id": "daqiq-test-v1",
        "payload": payload,
        "signature": sig_b64,
    }

    registry = KeyRegistry({"daqiq-test-v1": raw_pub_b64})
    verifier = LicenseVerifier(registry)

    raw_bytes = json.dumps(envelope_doc, ensure_ascii=False).encode("utf-8")
    env = verifier.parse_envelope_from_bytes(raw_bytes)

    res = verifier.validate_license(
        env,
        current_hardware_fingerprint=HWID_1,
        current_app_version="4.9.0",
        now_utc=datetime.datetime(2026, 11, 22, 1, 0, 0, tzinfo=datetime.timezone.utc),
    )

    assert res.is_valid is True
    assert res.status == ValidationStatus.VALID
    assert res.license.payload.license_id == "LIC-2026-TEST01"
    assert res.license.payload.customer.name == "فروشگاه تستی نمونه"


