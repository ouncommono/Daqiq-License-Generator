def test_cross_repo_tampering_rejected():
    """Verify Daqiq PR #38 verifier detects modified content as INVALID_SIGNATURE."""
    LicenseVerifier, KeyRegistry, ValidationStatus = _get_daqiq_verifier()

    vault, _ = KeyVault.create_vault(key_id="cross-key-v1", passphrase="Pass")
    registry = KeyRegistry({vault.key_id: vault.public_key_b64})
    verifier = LicenseVerifier(registry)

    spec = LicenseSpec(
        license_id="DQL-CROSS-TAMPER",
        customer_name="فروشگاه اصلی",
        license_type="perpetual",
        issued_at="2026-11-22T00:00:00Z",
        not_before="2026-11-22T00:00:00Z",
        expires_at=None,
        max_devices=1,
        device_fingerprints=[HWID_1],
        features={k: True for k in ALL_FEATURE_KEYS},
    )
    gen = LicenseBuilder.build_and_sign(spec, vault)

    # Tamper customer name in envelope JSON
    doc = json.loads(gen.json_text)
    doc["payload"]["customer"]["name"] = "فروشگاه هک‌شده"
    tampered_bytes = json.dumps(doc, ensure_ascii=False).encode("utf-8")

    envelope = verifier.parse_envelope_from_bytes(tampered_bytes)
    res = verifier.validate_license(envelope, current_hardware_fingerprint=HWID_1)

    assert res.is_valid is False
    assert res.status == ValidationStatus.INVALID_SIGNATURE
